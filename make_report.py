def p(text, bold=False, center=False, indent=True, before=0, after=0):
    par = doc.add_paragraph()
    par.alignment = WD_ALIGN_PARAGRAPH.CENTER if center else WD_ALIGN_PARAGRAPH.JUSTIFY
    pf = par.paragraph_format
    pf.space_before, pf.space_after = Pt(before), Pt(after)
    if indent and not center:
        pf.first_line_indent = Cm(1.25)
    r = par.add_run(text)
    r.bold = bold
    return par

def caption(text):
    return p(text, center=True, indent=False, before=2, after=8)

def heading(text):
    return p(text, bold=True, center=True, indent=False, before=10, after=6)

def table(headers, rows, widths):
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, hh in enumerate(headers):
        c = t.rows[0].cells[i]
        rn = c.paragraphs[0].add_run(hh)
        rn.bold = True
    for ri, row in enumerate(rows, 1):
        for ci, v in enumerate(row):
            t.rows[ri].cells[ci].paragraphs[0].add_run(str(v))
    for row in t.rows:
        for ci, w in enumerate(widths):
            row.cells[ci].width = Cm(w)
    return t

def figure(path, cap, width_cm=13.5):
    par = doc.add_paragraph()
    par.alignment = WD_ALIGN_PARAGRAPH.CENTER
    par.add_run().add_picture(path, width=Cm(width_cm))
    caption(cap)

def toc_field():
    par = doc.add_paragraph()
    run = par.add_run()
    f1 = OxmlElement('w:fldChar'); f1.set(qn('w:fldCharType'), 'begin')
    it = OxmlElement('w:instrText'); it.set(qn('xml:space'), 'preserve')
    it.text = 'TOC \\o "1-2" \\h \\z \\u'
    f2 = OxmlElement('w:fldChar'); f2.set(qn('w:fldCharType'), 'separate')
    r2 = OxmlElement('w:r'); t2 = OxmlElement('w:t')
    t2.text = 'Оновіть зміст: Ctrl+A, потім F9'
    r2.append(t2)
    f3 = OxmlElement('w:fldChar'); f3.set(qn('w:fldCharType'), 'end')
    run._r.append(f1); run._r.append(it); run._r.append(f2)
    par._p.append(r2); run2 = par.add_run(); run2._r.append(f3)

